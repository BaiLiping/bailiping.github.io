def Z_ROOF(x, y):
    zc = pchip([-1.092, -1.070, -1.040, -1.000, -0.950, -0.900, -0.600, -0.300, 0.000, 0.250, 0.450, 0.520, 0.560],
               [1.940, 1.980, 2.013, 2.034, 2.042, 2.045, 2.045, 2.042, 2.036, 2.028, 2.014, 2.001, 1.990])(x)
    ym = Y_DRIP(x)
    t = np.clip(np.abs(y) / ym, 0, 1)
    zd = np.minimum(Z_DRIP + 0.012, zc - 0.004)
    pw = np.interp(x, [-1.1, -0.6, 0.0, 0.5], [3.2, 3.8, 3.5, 2.8])
    return zc - (zc - zd) * t ** pw
