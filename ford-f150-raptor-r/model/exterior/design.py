def Z_HOOD(x, y):
    base = pchip([1.25, 1.50, 1.80, 2.10, 2.35, 2.50, 2.60, 2.66], [1.470, 1.468, 1.458, 1.432, 1.400, 1.372, 1.346, 1.322])(x)
    crown = 0.020 * (1 - np.clip(np.abs(y) / 0.85, 0, 1) ** 2)
    # power dome: plateau on the centre, fading forward
    amp = pchip([1.25, 1.45, 1.60, 1.72, 1.95, 2.10, 2.25, 2.42, 2.55], [0.004, 0.018, 0.036, 0.058, 0.046, 0.031, 0.019, 0.006, 0.0])(x)
    wy = 0.5 * (1 - np.tanh((np.abs(y) - 0.43) / 0.035))
    dome = amp * wy
    return base + crown + dome

