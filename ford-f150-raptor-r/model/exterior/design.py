def zone_w(x):
    """weights (bed, door, fender) blending smoothly across the panel gaps"""
    x = np.asarray(x, float)
    s = lambda a, w: 1 / (1 + np.exp(-(x - a) / w))
    wf = s(1.19, 0.004); wb = 1 - s(-1.165, 0.004); wd = 1 - wf - wb
    return wb, wd, wf
def Y_SIDE(x, z):
    wb, wd, wf = zone_w(x)
    return YP(x) + wb * I_BED(z) + wd * I_DOOR(z) + wf * I_FEN(z)

